-- 1. CATEGORÍAS DEL CATÁLOGO

CREATE TABLE IF NOT EXISTS catalog_categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- 2. ELEMENTOS DEL CATÁLOGO

CREATE TABLE IF NOT EXISTS catalog_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    category_id INTEGER NOT NULL,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    form_schema JSONB NOT NULL DEFAULT '{"fields":[]}'::jsonb,
    needs_approval BOOLEAN NOT NULL DEFAULT FALSE,
    sla_hours INTEGER,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_catalog_category
        FOREIGN KEY (category_id)
        REFERENCES catalog_categories(id),

    CONSTRAINT chk_catalog_sla_hours
        CHECK (sla_hours IS NULL OR sla_hours > 0),

    CONSTRAINT chk_catalog_form_schema
        CHECK (jsonb_typeof(form_schema) = 'object')
);


-- 3. SOLICITUDES DE SERVICIO

CREATE TABLE IF NOT EXISTS service_requests (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    key VARCHAR(20) NOT NULL UNIQUE,
    catalog_item_id UUID NOT NULL,
    form_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    status VARCHAR(30) NOT NULL DEFAULT 'submitted',
    requester_id UUID NOT NULL,
    assignee_id UUID,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fulfilled_at TIMESTAMP,

    CONSTRAINT fk_request_catalog_item
        FOREIGN KEY (catalog_item_id)
        REFERENCES catalog_items(id),

    CONSTRAINT chk_request_status
        CHECK (
            status IN (
                'submitted',
                'pending_approval',
                'approved',
                'rejected',
                'in_fulfillment',
                'fulfilled'
            )
        ),

    CONSTRAINT chk_request_form_data
        CHECK (jsonb_typeof(form_data) = 'object')
);


-- 4. APROBACIONES DE SOLICITUDES

CREATE TABLE IF NOT EXISTS request_approvals (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    request_id UUID NOT NULL,
    approver_id UUID NOT NULL,
    decision VARCHAR(10) NOT NULL,
    decided_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_approval_request
        FOREIGN KEY (request_id)
        REFERENCES service_requests(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_request_approval_decision
        CHECK (
            decision IN ('approved', 'rejected')
        )
);


-- 5. TAREAS DE CUMPLIMIENTO

CREATE TABLE IF NOT EXISTS fulfillment_tasks (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    request_id UUID NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    assignee_id UUID,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_fulfillment_request
        FOREIGN KEY (request_id)
        REFERENCES service_requests(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_fulfillment_status
        CHECK (
            status IN (
                'pending',
                'in_progress',
                'completed',
                'cancelled'
            )
        )
);


-- 6. ÍNDICES PARA CONSULTAS

CREATE INDEX IF NOT EXISTS idx_catalog_items_category
    ON catalog_items(category_id);

CREATE INDEX IF NOT EXISTS idx_catalog_items_active
    ON catalog_items(active);

CREATE INDEX IF NOT EXISTS idx_requests_status
    ON service_requests(status);

CREATE INDEX IF NOT EXISTS idx_requests_catalog_item
    ON service_requests(catalog_item_id);

CREATE INDEX IF NOT EXISTS idx_requests_requester
    ON service_requests(requester_id);

CREATE INDEX IF NOT EXISTS idx_requests_assignee
    ON service_requests(assignee_id);

CREATE INDEX IF NOT EXISTS idx_requests_created_at
    ON service_requests(created_at);

CREATE INDEX IF NOT EXISTS idx_request_approvals_request
    ON request_approvals(request_id);

CREATE INDEX IF NOT EXISTS idx_fulfillment_tasks_request
    ON fulfillment_tasks(request_id);
